// Command agentcatalog pins the Codex release runnerd may install. It reads
// each platform package from the npm registry, verifies the registry's
// signature over its integrity hash, and writes the Go catalog the runner
// checks downloads against. The runner never trusts registry metadata at
// install time; it trusts only the hashes compiled into it.
package main

import (
	"crypto/ecdsa"
	"crypto/sha256"
	"crypto/x509"
	"encoding/base64"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"net/url"
	"os"
	"regexp"
	"strings"
	"time"

	"codex-pool-proxy/internal/runner"
)

// npmSigningKeys are the registry keys published at
// https://registry.npmjs.org/-/npm/v1/keys, pinned so that a compromised
// mirror or proxy cannot vouch for its own hashes.
var npmSigningKeys = map[string]string{
	"SHA256:DhQ8wR5APBvFHLF/+Tc+AYvPOdTpcIDqOhxsBHRwC7U": "MFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEY6Ya7W++7aUPzvMTrezH6Ycx3c+HOKYCcNGybJZSCJq/fd7Qa8uuAKtdIkUQtQiEKERhAmE5lMMJhP8OkDOa2g==",
}

const registry = "https://registry.npmjs.org"
const output = "internal/runner/agent_catalog_generated.go"

type manifest struct {
	Name    string `json:"name"`
	Version string `json:"version"`
	Dist    struct {
		Integrity    string `json:"integrity"`
		Tarball      string `json:"tarball"`
		UnpackedSize int64  `json:"unpackedSize"`
		Signatures   []struct {
			KeyID string `json:"keyid"`
			Sig   string `json:"sig"`
		} `json:"signatures"`
	} `json:"dist"`
}

func main() {
	version := flag.String("codex", "", "Codex release to pin, such as 0.164.0")
	flag.Parse()
	if !regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`).MatchString(*version) {
		fail(errors.New("-codex must be a stable release version such as 0.164.0"))
	}
	client := &http.Client{Timeout: 60 * time.Second}
	var entries strings.Builder
	for _, p := range runner.CodexPlatforms() {
		m, err := fetch(client, *version+"-"+p.NPM)
		if err != nil {
			fail(fmt.Errorf("%s: %w", p.NPM, err))
		}
		if err := verify(m); err != nil {
			fail(fmt.Errorf("%s: %w", p.NPM, err))
		}
		digest, err := base64.StdEncoding.DecodeString(strings.TrimPrefix(m.Dist.Integrity, "sha512-"))
		if err != nil || len(digest) != 64 || !strings.HasPrefix(m.Dist.Integrity, "sha512-") || m.Dist.UnpackedSize <= 0 {
			fail(fmt.Errorf("%s: unusable integrity or size", p.NPM))
		}
		expected := registry + "/@openai/codex/-/codex-" + m.Version + ".tgz"
		if m.Dist.Tarball != expected {
			fail(fmt.Errorf("%s: unexpected tarball URL %s", p.NPM, m.Dist.Tarball))
		}
		fmt.Fprintf(&entries, "{Agent: \"codex\", Version: %q, GOOS: %q, GOARCH: %q, Package: %q, Triple: %q, SHA512: %q, UnpackedSize: %d},\n",
			*version, p.GOOS, p.GOARCH, m.Version, p.Triple, fmt.Sprintf("%x", digest), m.Dist.UnpackedSize)
	}
	source := fmt.Sprintf(`// Code generated by go run ./cmd/agentcatalog -codex %s; DO NOT EDIT.

package runner

var agentCatalog = []AgentRelease{
%s}
`, *version, entries.String())
	formatted, err := format.Source([]byte(source))
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(output, formatted, 0644); err != nil {
		fail(err)
	}
}

func fetch(client *http.Client, version string) (manifest, error) {
	var m manifest
	response, err := client.Get(registry + "/@openai%2fcodex/" + url.PathEscape(version))
	if err != nil {
		return m, err
	}
	defer response.Body.Close()
	if response.StatusCode != 200 {
		return m, fmt.Errorf("registry answered HTTP %d", response.StatusCode)
	}
	if err := json.NewDecoder(io.LimitReader(response.Body, 1<<20)).Decode(&m); err != nil {
		return m, err
	}
	if m.Name != "@openai/codex" || m.Version != version {
		return m, errors.New("registry returned another package")
	}
	return m, nil
}

// verify checks the registry signature over "<name>@<version>:<integrity>".
func verify(m manifest) error {
	message := sha256.Sum256([]byte(m.Name + "@" + m.Version + ":" + m.Dist.Integrity))
	for _, s := range m.Dist.Signatures {
		encoded, ok := npmSigningKeys[s.KeyID]
		if !ok {
			continue
		}
		der, _ := base64.StdEncoding.DecodeString(encoded)
		key, err := x509.ParsePKIXPublicKey(der)
		if err != nil {
			return err
		}
		signature, err := base64.StdEncoding.DecodeString(s.Sig)
		if err == nil && ecdsa.VerifyASN1(key.(*ecdsa.PublicKey), message[:], signature) {
			return nil
		}
	}
	return errors.New("no valid signature from a pinned npm registry key")
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "agentcatalog:", err)
	os.Exit(1)
}
